/**
 * @brief Computes z(x) polynomial
 *
 * See @cite lin1983error (Chapter 6 - BCH Codes) for more details.
 *
 * @param[out] z z(x) polynomial, array of PARAM_DELTA + 1 16-bits
 * N_SHARES-shares boolean-masked values
 * @param[in] sigma Error locator polynomial, array of 2^PARAM_FFT 16-bits
 * N_SHARES-shares boolean-masked values
 * @param[inout] degree Degree of error locator polynomial, 16-bits
 * N_SHARES-shares boolean-masked value (refreshed)
 * @param[inout] syndromes Syndromes, array of 2 * PARAM_DELTA 16-bits
 * N_SHARES-shares boolean-masked values (refreshed)
 */
void MSK_compute_z_poly(MSK_uint16_t z[PARAM_DELTA + 1],
                        const MSK_uint16_t sigma[PARAM_DELTA + 1],
                        MSK_uint16_t degree,
                        MSK_uint16_t syndromes[2 * PARAM_DELTA]) {
  MSK_uint16_t mask;
  MSK_uint16_t tmp;
  MSK_uint16_t tmp2;

  MSK_16b_mask(z[0], (uint16_t)1); // z[0] = 1;

  for (size_t i = 1; i < PARAM_DELTA + 1; ++i) {
    MSK_16b_mask(tmp, (uint16_t)(i - 1));
    MSK_16b_sub(tmp2, tmp, degree);
    MSK_SNI_16b_inplace_refresh(degree);
    MSK_16b_right_shift(tmp, tmp2, 15);
    MSK_16b_neg(mask, tmp); // mask = -((uint16_t) (i - degree - 1) >> 15);
    MSK_SNI_16b_and(z[i], mask, sigma[i]); // z[i] = mask & sigma[i];
  }

  MSK_16b_xor(z[1], z[1], syndromes[0]); // z[1] ^= syndromes[0];
  MSK_SNI_16b_inplace_refresh(syndromes[0]);

  for (size_t i = 2; i <= PARAM_DELTA; ++i) {
    MSK_16b_mask(tmp, (uint16_t)(i - 1));
    MSK_16b_sub(tmp2, tmp, degree);
    MSK_SNI_16b_inplace_refresh(degree);
    MSK_16b_right_shift(tmp, tmp2, 15);
    MSK_16b_neg(mask, tmp); // mask = -((uint16_t) (i - degree - 1) >> 15);
    MSK_SNI_16b_and(tmp, mask, syndromes[i - 1]);
    MSK_SNI_16b_inplace_refresh(syndromes[i - 1]);

    MSK_16b_xor(z[i], z[i], tmp); // z[i] ^= mask & syndromes[i - 1];

    for (size_t j = 1; j < i; ++j) {
      MSK_gf_mul(tmp, sigma[j], syndromes[i - j - 1]);
      MSK_SNI_16b_and(tmp2, mask, tmp);
      // z[i] ^= mask & PQCLEAN_HQC128_CLEAN_gf_mul(sigma[j], syndromes[i - j -
      // 1]);
      MSK_16b_xor(z[i], z[i], tmp2);
    }
  }
}

/**
 * @brief Computes the error values
 *
 * See @cite lin1983error (Chapter 6 - BCH Codes) for more details.
 *
 * @param[out] error_values Error values, array of PARAM_N1 16-bits
 * N_SHARES-shares boolean-masked values
 * @param[inout] z z(x) polynomial, array of PARAM_DELTA + 1 16-bits
 * N_SHARES-shares boolean-masked values (refreshed)
 * @param[in] [error] Error polynomial, array of 2^PARAM_M N_SHARES-shares
 * boolean-masked bytes
 */
void MSK_compute_error_values(MSK_uint16_t error_values[PARAM_N1],
                              MSK_uint16_t z[PARAM_DELTA + 1],
                              MSK_uint8_t error[1 << PARAM_M]) {
  MSK_uint16_t error16[1 << PARAM_M];
  MSK_8b_to_16b_copy_array(error16, error, 1 << PARAM_M);

  MSK_uint16_t beta_j[PARAM_DELTA] = {0};
  MSK_uint16_t e_j[PARAM_DELTA] = {0};

  MSK_uint16_t delta_counter = {0};
  MSK_uint16_t delta_real_value;
  MSK_uint16_t found;
  MSK_uint16_t mask1;
  MSK_uint16_t mask2;
  MSK_uint16_t tmp;
  MSK_uint16_t tmp2;
  MSK_uint16_t tmp3;
  MSK_uint16_t tmp4;
  MSK_uint16_t j_mask;
  MSK_uint16_t inverse;
  MSK_uint16_t inverse_power_j;

  MSK_uint16_t zero16 = {0};

  MSK_uint16_t ff16;
  MSK_16b_mask(ff16, (uint16_t)-1);

  for (size_t i = 0; i < PARAM_N1; i++) {
    MSK_16b_mask(found, 0); // found = 0;
    MSK_16b_eq(tmp, error16[i], zero16);
    MSK_SNI_16b_inplace_refresh(zero16);
    // mask1 = (uint16_t) (-((int32_t)error[i]) >> 31); error[i] != 0
    MSK_16b_if(mask1, zero16, ff16, tmp);

    for (size_t j = 0; j < PARAM_DELTA; j++) {
      MSK_16b_mask(j_mask, (uint16_t)j);
      MSK_16b_eq(tmp, j_mask, delta_counter);
      MSK_SNI_16b_inplace_refresh(delta_counter);
      MSK_SNI_16b_inplace_refresh(zero16);
      MSK_SNI_16b_inplace_refresh(ff16);
      // mask2 = ~((uint16_t) (-((int32_t) j ^ delta_counter) >> 31));
      // j == delta_counter
      MSK_16b_if(mask2, ff16, zero16, tmp);
      MSK_SNI_16b_inplace_refresh(ff16);

      MSK_16b_semi_and(tmp, mask2, gf_exp[i]);
      MSK_SNI_16b_and(tmp2, mask1, tmp);
      // beta_j[j] += mask1 & mask2 & gf_exp[i];
      MSK_16b_add(beta_j[j], beta_j[j], tmp2);

      MSK_SNI_16b_inplace_refresh(mask2);
      MSK_16b_semi_and(tmp, mask2, (uint16_t)1);
      MSK_SNI_16b_inplace_refresh(mask1);
      MSK_SNI_16b_and(tmp2, mask1, tmp);
      MSK_16b_add(found, found, tmp2); // found += mask1 & mask2 & 1;
    }
    // delta_counter += found;
    MSK_16b_add(delta_counter, delta_counter, found);
  }
  // delta_real_value = delta_counter;
  MSK_16b_to_16b_copy(delta_real_value, delta_counter);

  for (size_t i = 0; i < PARAM_DELTA; ++i) {
    MSK_16b_mask(tmp3, 1); // tmp3 = 1;
    MSK_16b_mask(tmp4, 1); // tmp4 = 1;
    // inverse = PQCLEAN_HQC128_CLEAN_gf_inverse(beta_j[i]);
    MSK_gf_inverse(inverse, beta_j[i]);
    MSK_16b_mask(inverse_power_j, 1); // inverse_power_j = 1;

    for (size_t j = 1; j <= PARAM_DELTA; ++j) {
      MSK_gf_mul(tmp, inverse_power_j, inverse);
      MSK_SNI_16b_inplace_refresh(inverse);
      // inverse_power_j = PQCLEAN_HQC128_CLEAN_gf_mul(inverse_power_j,
      // inverse);
      MSK_16b_to_16b_copy(inverse_power_j, tmp);
      MSK_gf_mul(tmp, inverse_power_j, z[j]);
      MSK_SNI_16b_inplace_refresh(z[j]);
      // tmp3 ^= PQCLEAN_HQC128_CLEAN_gf_mul(inverse_power_j, z[j]);
      MSK_16b_xor(tmp3, tmp3, tmp);
    }
    for (size_t k = 1; k < PARAM_DELTA; ++k) {
      MSK_gf_mul(tmp, inverse, beta_j[(i + k) % PARAM_DELTA]);
      MSK_SNI_16b_inplace_refresh(inverse);
      MSK_SNI_16b_inplace_refresh(beta_j[(i + k) % PARAM_DELTA]);
      tmp[0] ^= 1;
      MSK_gf_mul(tmp2, tmp4, tmp);
      // tmp4 = PQCLEAN_HQC128_CLEAN_gf_mul(tmp4, (1 ^
      // PQCLEAN_HQC128_CLEAN_gf_mul(inverse, beta_j[(i + k) % PARAM_DELTA])));
      MSK_16b_to_16b_copy(tmp4, tmp2);
    }

    MSK_uint16_t i_mask;
    MSK_16b_mask(i_mask, (uint16_t)(i + 1));
    MSK_16b_max(tmp, delta_real_value, i_mask);
    MSK_SNI_16b_inplace_refresh(delta_real_value);
    MSK_16b_eq(tmp2, tmp, delta_real_value);
    MSK_SNI_16b_inplace_refresh(delta_real_value);
    MSK_SNI_16b_inplace_refresh(zero16);
    MSK_SNI_16b_inplace_refresh(ff16);
    // mask1 = (uint16_t) (((int16_t) i - delta_real_value) >> 15);
    // i < delta_real_value
    MSK_16b_if(mask1, ff16, zero16, tmp2);

    MSK_gf_inverse(tmp, tmp4);
    MSK_gf_mul(tmp2, tmp3, tmp);
    // e_j[i] = mask1 & PQCLEAN_HQC128_CLEAN_gf_mul(tmp3,
    // PQCLEAN_HQC128_CLEAN_gf_inverse(tmp4));
    MSK_SNI_16b_and(e_j[i], mask1, tmp2);
  }

  MSK_16b_mask(delta_counter, 0); // delta_counter = 0;
  for (size_t i = 0; i < PARAM_N1; ++i) {
    MSK_16b_mask(found, 0); // found = 0;
    MSK_SNI_16b_inplace_refresh(zero16);
    MSK_16b_eq(tmp, error16[i], zero16);
    MSK_SNI_16b_inplace_refresh(zero16);
    MSK_SNI_16b_inplace_refresh(ff16);
    // mask1 = (uint16_t) (-((int32_t)error[i]) >> 31);
    // error[i] != 0
    MSK_16b_if(mask1, zero16, ff16, tmp);

    for (size_t j = 0; j < PARAM_DELTA; j++) {
      MSK_16b_mask(j_mask, (uint16_t)j);

      MSK_16b_eq(tmp, j_mask, delta_counter);
      MSK_SNI_16b_inplace_refresh(delta_counter);
      MSK_SNI_16b_inplace_refresh(zero16);
      MSK_SNI_16b_inplace_refresh(ff16);
      // mask2 = ~((uint16_t) (-((int32_t) j ^ delta_counter) >> 31));
      // j == delta_counter
      MSK_16b_if(mask2, ff16, zero16, tmp);
      MSK_SNI_16b_and(tmp, mask2, e_j[j]);
      MSK_SNI_16b_inplace_refresh(e_j[j]);
      MSK_SNI_16b_and(tmp2, mask1, tmp);
      // error_values[i] += mask1 & mask2 & e_j[j];
      MSK_16b_add(error_values[i], error_values[i], tmp2);

      MSK_16b_semi_and(tmp, mask2, 1);
      MSK_SNI_16b_inplace_refresh(mask1);
      MSK_SNI_16b_and(tmp2, mask1, tmp);
      MSK_16b_add(found, found, tmp2); // found += mask1 & mask2 & 1;
    }
    // delta_counter += found;
    MSK_16b_add(delta_counter, delta_counter, found);
  }
}

/**
 * @brief Correct errors
 *
 * @param[out] [cdw] Corrected codeword, array of PARAM_N1 N_SHARES-shares
 * boolean-masked bytes
 * @param[in] [error_values] Error, array of PARAM_DELTA 16-bits N_SHARES-shares
 * boolean-masked values
 */
void MSK_correct_errors(MSK_uint8_t cdw[PARAM_N1],
                        const MSK_uint16_t error_values[PARAM_N1]) {
  MSK_uint16_t tmp_cdw16;
  for (size_t i = 0; i < PARAM_N1; ++i) {
    MSK_8b_to_16b_copy(tmp_cdw16, cdw[i]);
    // cdw[i] ^= error_values[i];
    MSK_16b_xor(tmp_cdw16, tmp_cdw16, error_values[i]);
    MSK_16b_to_8b_copy(cdw[i], tmp_cdw16);
  }
}

void MSK_reed_solomon_decode(MSK_uint8_t msg[PARAM_K],
                             MSK_uint8_t cdw[PARAM_N1]) {
  MSK_uint16_t syndromes[2 * PARAM_DELTA] = {0};
  MSK_uint16_t sigma[1 << PARAM_FFT] = {0};
  MSK_uint8_t error[1 << PARAM_M] = {0};
  MSK_uint16_t z[PARAM_N1] = {0};
  MSK_uint16_t error_values[PARAM_N1] = {0};
  MSK_uint16_t deg;

  // Calculate the 2*PARAM_DELTA syndromes
  MSK_rs_compute_syndromes(syndromes, cdw);

  // Compute the error locator polynomial sigma
  // Sigma's degree is at most PARAM_DELTA but the FFT requires the extra room
  // deg = compute_elp(sigma, syndromes);
  MSK_compute_elp(sigma, deg, syndromes);

  // Compute the error polynomial error
  MSK_compute_roots(error, sigma);

  // Compute the polynomial z(x)
  MSK_SNI_16b_inplace_refresh_array(sigma, PARAM_DELTA + 1);
  MSK_compute_z_poly(z, sigma, deg, syndromes);

  // Compute the error values
  MSK_compute_error_values(error_values, z, error);

  // Correct the errors
  MSK_correct_errors(cdw, error_values);

  // Retrieve the message from the decoded codeword
  MSK_8b_to_8b_copy_array(msg, cdw + PARAM_G - 1, PARAM_K);
  // No path from input to output. Since RS_decode is always called in tandem
  // with RM_decode, the below refresh suffices to de-correlate input and
  // output of the decoder.
  MSK_SNI_8b_inplace_refresh_array(msg, PARAM_K);

  // Debug
#if VERBOSITY_LEVEL != 0
  printf("\n\nThe syndromes: ");
  for (size_t i = 0; i < 2 * PARAM_DELTA; ++i) {
    printf("%u ", MSK_16b_unmask(syndromes[i]));
  }
  printf("\n\nThe error locator polynomial: sigma(x) = ");
  bool first_coeff = true;
  if (MSK_16b_unmask(sigma[0])) {
    printf("%u", MSK_16b_unmask(sigma[0]));
    first_coeff = false;
  }
  for (size_t i = 1; i < (1 << PARAM_FFT); ++i) {
    if (MSK_16b_unmask(sigma[i]) == 0)
      continue;
    if (!first_coeff)
      printf(" + ");
    first_coeff = false;
    if (MSK_16b_unmask(sigma[i]) != 1)
      printf("%u ", MSK_16b_unmask(sigma[i]));
    if (i == 1)
      printf("x");
    else
      printf("x^%zu", i);
  }
  if (first_coeff)
    printf("0");

  printf("\n\nThe polynomial: z(x) = ");
  bool first_coeff_1 = true;
  if (MSK_16b_unmask(z[0])) {
    printf("%u", MSK_16b_unmask(z[0]));
    first_coeff_1 = false;
  }
  for (size_t i = 1; i < (PARAM_DELTA + 1); ++i) {
    if (MSK_16b_unmask(z[i]) == 0)
      continue;
    if (!first_coeff_1)
      printf(" + ");
    first_coeff_1 = false;
    if (MSK_16b_unmask(z[i]) != 1)
      printf("%u ", MSK_16b_unmask(z[i]));
    if (i == 1)
      printf("x");
    else
      printf("x^%zu", i);
  }
  if (first_coeff_1)
    printf("0");

  printf("\n\nThe pairs of (error locator numbers, error values): ");
  size_t j = 0;
  for (size_t i = 0; i < PARAM_N1; ++i) {
    if (MSK_8b_unmask(error[i])) {
      printf("(%zu, %d) ", i, MSK_16b_unmask(error_values[j]));
      j++;
    }
  }
  printf("\n");
#endif
}
